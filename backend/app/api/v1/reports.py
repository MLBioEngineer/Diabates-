"""
Clinical Health Report generation and Data Export Endpoints
"""

import uuid
from datetime import datetime, timezone
from fastapi import APIRouter, Depends, Response
from sqlalchemy import select, desc
from sqlalchemy.ext.asyncio import AsyncSession

from backend.app.core.database import get_db
from backend.app.models.patient import PatientProfile
from backend.app.models.user import User
from backend.app.models.telemetry import TelemetryReading
from backend.app.models.risk_assessment import RiskAssessment
from backend.app.models.alert import HealthAlert
from backend.app.schemas.report import HealthReportOut
from backend.app.schemas.telemetry import TelemetryOut
from backend.app.schemas.alert import AlertOut
from backend.app.schemas.ml import RiskPredictionOutput, SHAPContribution
from backend.app.services.telemetry_service import TelemetryService
from backend.app.api.v1.deps import get_current_user, get_current_patient_profile

router = APIRouter()


@router.get("/summary", response_model=HealthReportOut)
async def get_clinical_health_report(
    current_user: User = Depends(get_current_user),
    current_patient: PatientProfile = Depends(get_current_patient_profile),
    db: AsyncSession = Depends(get_db),
):
    # 1. Telemetry stats
    stats = await TelemetryService.get_patient_statistics(db, current_patient.id, hours=48)

    # 2. Latest Risk Assessment
    risk_q = (
        select(RiskAssessment)
        .where(RiskAssessment.patient_id == current_patient.id)
        .order_by(desc(RiskAssessment.created_at))
        .limit(1)
    )
    risk_res = await db.execute(risk_q)
    risk_obj = risk_res.scalars().first()
    latest_risk_dto = None
    if risk_obj:
        shap_list = [SHAPContribution(**item) for item in (risk_obj.shap_top_contributors or [])]
        latest_risk_dto = RiskPredictionOutput(
            id=risk_obj.id,
            patient_id=risk_obj.patient_id,
            model_name=risk_obj.model_name,
            risk_score=risk_obj.risk_score,
            risk_percentage=round(risk_obj.risk_score * 100.0, 1),
            risk_category=risk_obj.risk_category,
            clinical_summary=risk_obj.clinical_summary,
            disclaimer="Automated research decision support only.",
            shap_contributions=shap_list,
            created_at=risk_obj.created_at,
        )

    # 3. Recent 20 readings
    read_q = (
        select(TelemetryReading)
        .where(TelemetryReading.patient_id == current_patient.id)
        .order_by(desc(TelemetryReading.recorded_at))
        .limit(20)
    )
    read_res = await db.execute(read_q)
    recent_readings = [TelemetryOut.model_validate(r) for r in read_res.scalars().all()]

    # 4. Recent alerts
    alert_q = (
        select(HealthAlert)
        .where(HealthAlert.patient_id == current_patient.id)
        .order_by(desc(HealthAlert.created_at))
        .limit(10)
    )
    alert_res = await db.execute(alert_q)
    recent_alerts = [AlertOut.model_validate(a) for a in alert_res.scalars().all()]

    # Clinical Notes synthesis
    notes = (
        f"Patient exhibits a Time-in-Range (70-180 mg/dL) of {stats.time_in_range_percent}%. "
        f"Mean interstitial glucose is {stats.mean_glucose} mg/dL with an estimated Glucose Management Indicator (GMI) of {stats.glucose_management_indicator}%. "
        f"Glycemic variability coefficient of variation (%CV) is {stats.glycemic_variability_cv}%. "
    )
    if stats.time_below_range_percent > 4.0:
        notes += "ATTENTION: Elevated hypoglycemia exposure (> 4% below range) requires clinical evaluation."

    return HealthReportOut(
        report_id=f"REP-{uuid.uuid4().hex[:8].upper()}",
        generated_at=datetime.now(timezone.utc),
        patient_name=current_user.full_name,
        patient_id=current_patient.id,
        diabetes_type=current_patient.diabetes_type,
        monitoring_period="Last 48 Hours Continuous Monitoring",
        telemetry_statistics=stats,
        latest_risk_assessment=latest_risk_dto,
        recent_readings_sample=recent_readings,
        recent_alerts=recent_alerts,
        clinical_notes=notes,
        disclaimer="INFORMATIONAL ONLY: Generated by AI Clinical Decision Support System prototype. Not a substitute for formal diagnostic testing.",
    )


@router.get("/export-csv")
async def export_telemetry_csv(
    current_patient: PatientProfile = Depends(get_current_patient_profile),
    db: AsyncSession = Depends(get_db),
):
    query = (
        select(TelemetryReading)
        .where(TelemetryReading.patient_id == current_patient.id)
        .order_by(desc(TelemetryReading.recorded_at))
        .limit(500)
    )
    res = await db.execute(query)
    readings = res.scalars().all()

    csv_lines = [
        "Recorded At,Glucose (mg/dL),Velocity (mg/dL/min),Heart Rate (BPM),Blood Pressure (Sys/Dia),Temperature (C),SpO2 (%),Steps,Provenance"
    ]
    for r in readings:
        csv_lines.append(
            f"{r.recorded_at.isoformat()},{r.glucose_mg_dl},{r.glucose_trend_velocity},{r.heart_rate_bpm},{r.blood_pressure_systolic}/{r.blood_pressure_diastolic},{r.body_temperature_c},{r.spo2_percentage},{r.physical_activity_steps},{r.provenance}"
        )

    content = "\n".join(csv_lines)
    return Response(
        content=content,
        media_type="text/csv",
        headers={"Content-Disposition": f"attachment; filename=telemetry_export_{current_patient.id[:8]}.csv"},
    )
